"""Postgres (Supabase) behind the same interface as the sqlite3 connection the rest of Kompas uses.

The code base writes SQLite SQL. This module makes it run on Postgres:
- `?` placeholders become `%s`, and LIKE becomes ILIKE (SQLite's LIKE ignores ASCII case).
- json_extract(text, '$.key') exists as a SQL function, returning text.
- Rows answer to row["name"], row[0] and dict(row), like sqlite3.Row.
- Transactions start before INSERT/UPDATE/DELETE and end at commit(), as in sqlite3. BEGIN IMMEDIATE takes
  an advisory lock, so writers that relied on SQLite's write lock are still serialised.
- The schema is derived from db.SCHEMA and its migrations, so the two databases can't drift apart.

Connections come from a pool (one per process): db.connect() is called per API request, and a new TLS
connection to Supabase each time would cost more than the query."""

import functools
import hashlib
import os
import re
import sqlite3
import threading

import psycopg
from psycopg.types.numeric import FloatLoader
from psycopg_pool import ConnectionPool

from . import db

LOCK_KEY = 0x6B6F6D706173   # "kompas": the advisory lock behind BEGIN IMMEDIATE
# COLLATE "C": compare and sort text bytewise, as SQLite does (timestamps are ISO strings compared as text)
TYPES = {"TEXT": 'text COLLATE "C"', "INTEGER": "bigint", "REAL": "double precision"}

JSON_EXTRACT = """
CREATE OR REPLACE FUNCTION json_extract(doc text, path text) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path = pg_catalog
AS $$ SELECT (doc::jsonb) #>> string_to_array(substr(path, 3), '.') $$
"""

_pools: dict[str, ConnectionPool] = {}
_pools_lock = threading.Lock()


# ---------- schema ----------


SET_VERSION = ("INSERT INTO meta (key, value) VALUES ('schema_version', '{}') "
               "ON CONFLICT (key) DO UPDATE SET value = excluded.value")


@functools.cache
def schema() -> tuple[str, dict[str, dict[str, str]]]:
    """(DDL script, {table: {column: declaration}}) for the current SQLite schema. The script creates what is
    missing; columns a later migration added to an existing table are added by _create_schema."""
    lite = sqlite3.connect(":memory:")
    lite.row_factory = sqlite3.Row
    db.init(lite)
    out, columns = [JSON_EXTRACT], {}
    tables = lite.execute("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' "
                          "ORDER BY rowid").fetchall()
    for t in tables:
        name = t["name"]
        cols = lite.execute(f"PRAGMA table_info({name})").fetchall()
        pk = [c["name"] for c in sorted((c for c in cols if c["pk"]), key=lambda c: c["pk"])]
        identity = pk[0] if len(pk) == 1 and "AUTOINCREMENT" in t["sql"].upper() else None
        defs = {c["name"]: _column(c, c["name"] == identity) for c in cols}
        parts = [f"{n} {d}" for n, d in defs.items()]
        if pk:
            parts.append(f"PRIMARY KEY ({', '.join(pk)})")
        for ix in lite.execute(f"PRAGMA index_list({name})").fetchall():
            if ix["origin"] == "u":
                ix_cols = [r["name"] for r in lite.execute(f"PRAGMA index_info({ix['name']})")]
                parts.append(f"UNIQUE ({', '.join(ix_cols)})")
        out.append(f"CREATE TABLE IF NOT EXISTS {name} (\n  " + ",\n  ".join(parts) + "\n)")
        # Supabase serves the public schema over its REST API; with RLS on and no policies, only the
        # database owner (this backend) can read or write the tables.
        out.append(f"ALTER TABLE {name} ENABLE ROW LEVEL SECURITY")
        columns[name] = {n: d for n, d in defs.items() if n != identity}
    for ix in lite.execute("SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL"):
        out.append(re.sub(r"^CREATE INDEX (IF NOT EXISTS )?", "CREATE INDEX IF NOT EXISTS ", ix["sql"]))
    out.append(SET_VERSION.format(db.SCHEMA_VERSION))
    lite.close()
    return ";\n".join(out), columns


def _column(c, identity: bool) -> str:
    if identity:
        return "bigint GENERATED BY DEFAULT AS IDENTITY"
    decl = TYPES.get(c["type"].upper(), TYPES["TEXT"])
    if c["notnull"] and not c["pk"]:
        decl += " NOT NULL"
    if c["dflt_value"] is not None:
        decl += f" DEFAULT {c['dflt_value']}"
    return decl


def _schema_hash(script: str) -> str:
    return hashlib.sha256(script.encode()).hexdigest()[:16]


def _schema_current(conn: psycopg.Connection, script: str) -> bool:
    """True when this exact schema script was already applied. The script's ALTER TABLE statements need an
    exclusive lock on every table, so re-running them on each server start would wait behind any ingestion or
    snapshot write in progress until Supabase's statement timeout cancels the start."""
    try:
        row = conn.execute("SELECT value FROM meta WHERE key = 'pg_schema_hash'").fetchone()
    except psycopg.errors.UndefinedTable:
        return False
    return row is not None and row[0] == _schema_hash(script)


def _create_schema(conn: psycopg.Connection):
    script, columns = schema()
    if _schema_current(conn, script):
        return
    with conn.transaction():
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (LOCK_KEY,))   # several processes may start at once
        conn.execute(script)   # no parameters: psycopg sends it as one multi-statement query
        have = {(r[0], r[1]) for r in conn.execute(
            "SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = current_schema()")}
        for table, defs in columns.items():
            for col, decl in defs.items():
                if (table, col) not in have:
                    conn.execute(f"ALTER TABLE {table} ADD COLUMN {col} {decl}")
        conn.execute("INSERT INTO meta (key, value) VALUES ('pg_schema_hash', %s) "
                     "ON CONFLICT (key) DO UPDATE SET value = excluded.value", (_schema_hash(script),))


# ---------- SQL translation ----------


@functools.lru_cache(maxsize=1024)
def translate(sql: str) -> str:
    """SQLite SQL with ? placeholders -> psycopg SQL with %s. Text inside quotes is left alone, apart from
    escaping % (queries always go with a parameter list, so psycopg reads every %)."""
    out, i, n = [], 0, len(sql)
    while i < n:
        ch = sql[i]
        if ch in "'\"":
            j = sql.index(ch, i + 1) + 1 if ch in sql[i + 1:] else n
            out.append(sql[i:j].replace("%", "%%"))
            i = j
            continue
        j = i
        while j < n and sql[j] not in "'\"":
            j += 1
        chunk = sql[i:j].replace("%", "%%").replace("?", "%s")
        out.append(re.sub(r"\bLIKE\b", "ILIKE", chunk, flags=re.IGNORECASE))
        i = j
    return "".join(out)


def _params(params):
    return [int(p) if isinstance(p, bool) else p for p in params]


# ---------- rows, cursors, connections ----------


class Row:
    """sqlite3.Row's interface: row["name"], row[0], iteration, keys() and dict(row)."""
    __slots__ = ("_index", "_values")

    def __init__(self, index: dict[str, int], values):
        self._index, self._values = index, values

    def __getitem__(self, key):
        return self._values[key] if isinstance(key, (int, slice)) else self._values[self._index[key]]

    def keys(self):
        return list(self._index)

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def __eq__(self, other):
        return isinstance(other, Row) and self._index == other._index and tuple(self._values) == tuple(other._values)

    def __repr__(self):
        return f"Row({dict(zip(self._index, self._values))})"


def _row_factory(cursor):
    index = {d.name: i for i, d in reversed(list(enumerate(cursor.description or [])))}   # first wins, as in SQLite
    return lambda values: Row(index, values)


class Cursor:
    def __init__(self, cur: psycopg.Cursor | None):
        self._cur = cur

    @property
    def rowcount(self) -> int:
        return self._cur.rowcount if self._cur else -1

    def fetchone(self):
        return self._cur.fetchone() if self._cur and self._cur.description else None

    def fetchall(self) -> list:
        return self._cur.fetchall() if self._cur and self._cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


class Connection:
    """A pooled Postgres connection that behaves like the sqlite3 connections db.connect() returns."""

    def __init__(self, pool: ConnectionPool):
        self._pool = pool
        self._conn: psycopg.Connection | None = pool.getconn()
        self._in_tx = False
        self._lock = threading.RLock()

    def _live(self) -> psycopg.Connection:
        if self._conn is None:
            raise psycopg.InterfaceError("connection is closed")
        if not self._in_tx and (self._conn.closed or self._conn.broken):
            self._pool.putconn(self._conn)
            self._conn = self._pool.getconn()
        return self._conn

    def _run(self, fn):
        with self._lock:
            fresh = not self._in_tx
            try:
                return fn(self._live())
            except psycopg.OperationalError:
                if not (fresh and self._conn.broken):
                    raise
                self._in_tx = False   # the server dropped an idle connection: nothing was lost, try once more
                return fn(self._live())

    def _begin_if_writing(self, conn, sql: str):
        if not self._in_tx and sql.lstrip()[:6].upper() in ("INSERT", "UPDATE", "DELETE"):
            conn.execute("BEGIN")
            self._in_tx = True

    def execute(self, sql: str, params=()) -> Cursor:
        word = sql.strip().upper()
        if word in ("BEGIN", "BEGIN IMMEDIATE"):
            def begin(conn):
                conn.execute("BEGIN")
                self._in_tx = True
                if word == "BEGIN IMMEDIATE":
                    conn.execute("SELECT pg_advisory_xact_lock(%s)", (LOCK_KEY,))
            self._run(begin)
            return Cursor(None)
        if word == "COMMIT":
            self.commit()
            return Cursor(None)
        if word == "ROLLBACK":
            self.rollback()
            return Cursor(None)
        if word.startswith("PRAGMA"):
            return Cursor(None)

        def run(conn):
            self._begin_if_writing(conn, sql)
            return Cursor(conn.execute(translate(sql), _params(params)))
        return self._run(run)

    def executemany(self, sql: str, seq) -> Cursor:
        rows = [_params(p) for p in seq]

        def run(conn):
            self._begin_if_writing(conn, sql)
            cur = conn.cursor()
            if rows:
                cur.executemany(translate(sql), rows)
            return Cursor(cur)
        return self._run(run)

    def executescript(self, script: str):
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)
        self.commit()

    def commit(self):
        with self._lock:
            if self._in_tx:
                self._in_tx = False
                self._conn.execute("COMMIT")

    def rollback(self):
        with self._lock:
            if self._in_tx:
                self._in_tx = False
                self._conn.execute("ROLLBACK")

    def close(self):
        with self._lock:
            if self._conn is None:
                return
            try:
                self.rollback()
            except psycopg.Error:
                pass
            self._pool.putconn(self._conn)
            self._conn = None

    @property
    def raw(self) -> psycopg.Connection:
        """The psycopg connection underneath, for COPY and other Postgres-only work."""
        return self._live()


def _configure(conn: psycopg.Connection):
    conn.adapters.register_loader("numeric", FloatLoader)   # SUM/AVG give numeric; the code expects floats
    conn.row_factory = _row_factory


def pool(url: str) -> ConnectionPool:
    with _pools_lock:
        if url not in _pools:
            # prepare_threshold=None: no server-side prepared statements, which Supabase's pooler may not keep
            p = ConnectionPool(url, min_size=1, max_size=int(os.environ.get("KOMPAS_PG_POOL", "8")),
                               kwargs={"autocommit": True, "prepare_threshold": None}, configure=_configure,
                               check=ConnectionPool.check_connection, open=True, name="kompas")
            try:
                with p.connection() as conn:
                    _create_schema(conn)
            except BaseException:
                p.close()   # the next request tries again with a new pool
                raise
            _pools[url] = p
        return _pools[url]


def connect(url: str) -> Connection:
    return Connection(pool(url))


def close_pools():
    with _pools_lock:
        for p in _pools.values():
            p.close()
        _pools.clear()


# ---------- one-off copy from the SQLite file ----------


def copy_from_sqlite(src: sqlite3.Connection, url: str, replace: bool = False) -> dict[str, tuple[int, int]]:
    """Copies every table of a SQLite database into Postgres, in one transaction. Returns
    {table: (rows in SQLite, rows in Postgres)}. Refuses to overwrite data unless replace is set."""
    tables = [r[0] for r in src.execute("SELECT name FROM sqlite_master WHERE type = 'table' "
                                        "AND name NOT LIKE 'sqlite_%' ORDER BY rowid")]
    pg = connect(url)
    conn = pg.raw
    try:
        with conn.transaction():
            have = {t: conn.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in tables}
            if any(n for t, n in have.items() if t != "meta") and not replace:
                raise RuntimeError("Postgres already holds data: "
                                   + ", ".join(f"{t}={n}" for t, n in have.items() if n) + " (use --replace)")
            conn.execute(f"TRUNCATE {', '.join(tables)} RESTART IDENTITY")
            for t in tables:
                src_cols = [r[1] for r in src.execute(f"PRAGMA table_info({t})")]
                pg_cols = {r[0]: r[1] for r in conn.execute(
                    "SELECT column_name, is_identity FROM information_schema.columns "
                    "WHERE table_schema = current_schema() AND table_name = %s", (t,))}
                cols = [c for c in src_cols if c in pg_cols]
                with conn.cursor().copy(f"COPY {t} ({', '.join(cols)}) FROM STDIN") as cp:
                    for row in src.execute(f"SELECT {', '.join(cols)} FROM {t}"):
                        cp.write_row(tuple(row))
                for c, is_identity in pg_cols.items():
                    if is_identity == "YES":   # the next id continues after the copied ones
                        conn.execute(f"SELECT setval(pg_get_serial_sequence('{t}', '{c}'), "
                                     f"COALESCE(MAX({c}), 0) + 1, false) FROM {t}")
            conn.execute(SET_VERSION.format(db.SCHEMA_VERSION))   # the version this checkout's schema is at
        return {t: (src.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0],
                    conn.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]) for t in tables}
    finally:
        pg.close()
